source("00_config.R", encoding = "UTF-8")
dumpsite_file <- file.path(DIRS["vectors"], "dumpsite.gpkg")
if (!file.exists(dumpsite_file)) stop("Run stage 02 first; missing: ", dumpsite_file)
dumpsite <- terra::vect(dumpsite_file)
if (terra::is.lonlat(dumpsite)) dumpsite <- terra::project(dumpsite, MAP_CRS)
buffered <- make_dumpsite_buffer(dumpsite, BOUNDARY_BUFFER_M)
if (file.exists(BUFFER_VECTOR)) file.remove(BUFFER_VECTOR)
terra::writeVector(buffered, BUFFER_VECTOR, filetype = "GPKG", overwrite = TRUE)
message("Created reproducible ", BOUNDARY_BUFFER_M, " m buffer: ", BUFFER_VECTOR)
